          </p>
        </div>
      </div>
      <div class="card">
        <div class="card-body">
          <span class="card-tag" style="font-size:1.1rem;font-weight:700;">02</span>
          <h3 class="card-title">Circular Intarsia Knitting</h3>
          <p class="card-desc">
